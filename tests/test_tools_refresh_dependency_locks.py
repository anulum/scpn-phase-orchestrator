class TestLockTable:
    def test_every_generated_lock_is_listed_once(self) -> None:
        listed = [spec.name for spec in mod.LOCKS]
        assert len(listed) == len(set(listed))
        assert set(listed) == _generated_lockfiles()

    def test_hand_maintained_pin_lists_stay_outside_the_table(self) -> None:
        listed = {spec.name for spec in mod.LOCKS}
        for name in ("ci-tools.txt", "docs-tools.txt"):
            assert (REQUIREMENTS / name).is_file()
            assert name not in listed
            assert name not in _generated_lockfiles()

    @pytest.mark.parametrize("spec", mod.LOCKS, ids=lambda spec: spec.name)
    def test_command_matches_committed_header(self, spec: object) -> None:
        command = mod.build_command(spec, uvx="uvx", uv="uv")
        recorded = _recorded_command(ROOT / spec.output)
        if spec.generator == "uv":
            assert command == recorded
        else:
            # The pinned pip-tools release records ``--no-index`` in the header
            # next to ``--no-emit-index-url`` although the tool never passes it;
            # every lock regenerated by the tool therefore carries it.
            assert "--no-index" in recorded
            assert [part for part in recorded if part != "--no-index"] == [
                "pip-compile",
                *spec.arguments,
            ]
            assert command[-len(spec.arguments) :] == list(spec.arguments)

    @pytest.mark.parametrize("spec", mod.LOCKS, ids=lambda spec: spec.name)
    def test_header_interpreter_matches_table(self, spec: object) -> None:
        text = (ROOT / spec.output).read_text(encoding="utf-8")
        if spec.generator == "pip-compile":
            assert f"autogenerated by pip-compile with Python {spec.python}\n" in text
        else:
            assert ["--python-version", spec.python] == list(spec.arguments[2:4])

    @pytest.mark.parametrize("spec", mod.LOCKS, ids=lambda spec: spec.name)
    def test_every_input_is_committed_in_the_repository(self, spec: object) -> None:
        source = next(
            arg
            for arg in reversed(spec.arguments)
            if arg.endswith((".in", "pyproject.toml"))
        )
        assert not Path(source).is_absolute()
        assert (ROOT / source).is_file()

    def test_constraint_source_is_refreshed_before_its_consumers(self) -> None:
        order = [spec.output for spec in mod.LOCKS]
        dev = order.index("requirements/dev-lock.txt")
        for spec in mod.LOCKS:
            if "--constraint=requirements/dev-lock.txt" in spec.arguments:
                assert order.index(spec.output) > dev

    def test_pip_tools_version_is_documented(self) -> None:
        guide = (ROOT / "docs" / "guide" / "dependency_locks.md").read_text(
            encoding="utf-8"
        )
        assert f"pip-tools {mod.PIP_TOOLS_VERSION}" in guide

    def test_make_target_delegates_to_the_tool(self) -> None:
        makefile = (ROOT / "Makefile").read_text(encoding="utf-8")
        recipe = makefile.split("\nlock-refresh:", 1)[1].split("\n\n", 1)[0]
        assert "tools/refresh_dependency_locks.py" in recipe
        assert "pip-compile " not in recipe


