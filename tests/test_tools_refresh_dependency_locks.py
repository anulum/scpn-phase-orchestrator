# SCPN Phase Orchestrator — Tests for refresh_dependency_locks.py

"""Tests for ``tools/refresh_dependency_locks.py``.

The lock table is checked against the committed lockfiles themselves: every
generated lock under ``requirements/`` must be listed, and the command the tool
would run must equal the command recorded in that lock's header. Licence-block
preservation is exercised on the real committed bytes, and the CLI is run as a
subprocess.
"""

from __future__ import annotations

import importlib.util
import os
import runpy
import shlex
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "tools" / "refresh_dependency_locks.py"
REQUIREMENTS = ROOT / "requirements"


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "_refresh_dependency_locks_test_mod", SCRIPT
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


mod = _load()


def _recorded_command(path: Path) -> list[str]:
    """Return the generator command recorded in a committed lock header."""
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.removeprefix("#").strip()
        if stripped.startswith(("pip-compile ", "uv pip compile ")):
            return shlex.split(stripped)
    raise AssertionError(f"no generator command in {path.name}")


def _generated_lockfiles() -> set[str]:
    names = set()
    for path in REQUIREMENTS.glob("*.txt"):
        text = path.read_text(encoding="utf-8")
        if mod.PIP_COMPILE_HEADER in text or mod.UV_HEADER in text:
            names.add(path.name)
    return names


