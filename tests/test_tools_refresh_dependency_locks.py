def _copy_lock(tmp_path: Path, name: str) -> tuple[Path, str]:
    target = tmp_path / "requirements" / name
    target.parent.mkdir(parents=True)
    text = (REQUIREMENTS / name).read_text(encoding="utf-8")
    target.write_text(text, encoding="utf-8")
    return target, text


class TestRefreshLock:
    def test_prefix_survives_a_generator_rewrite(self, tmp_path: Path) -> None:
        spec = mod.select_locks(["studio-sdk.txt"])[0]
        target, original = _copy_lock(tmp_path, spec.name)
        prefix = mod.preserved_prefix(original, "pip-compile")
        commands: list[list[str]] = []

        def rewrite_like_pip_compile(command: list[str], root: Path) -> None:
            commands.append(command)
            assert root == tmp_path
            target.write_text(original[len(prefix) :], encoding="utf-8")

        mod.refresh_lock(
            spec, tmp_path, uvx="uvx", uv="uv", runner=rewrite_like_pip_compile
        )
        assert target.read_text(encoding="utf-8") == original
        assert commands == [mod.build_command(spec, uvx="uvx", uv="uv")]

    def test_generator_failure_restores_committed_bytes(self, tmp_path: Path) -> None:
        spec = mod.select_locks(["runtime-lock.txt"])[0]
        target, original = _copy_lock(tmp_path, spec.name)

        def failing_generator(command: list[str], root: Path) -> None:
            target.write_text("partial output\n", encoding="utf-8")
            raise subprocess.CalledProcessError(1, command)

        with pytest.raises(subprocess.CalledProcessError):
            mod.refresh_lock(
                spec, tmp_path, uvx="uvx", uv="uv", runner=failing_generator
            )
        assert target.read_text(encoding="utf-8") == original

    def test_foreign_leading_text_is_refused_and_rolled_back(
        self, tmp_path: Path
    ) -> None:
        spec = mod.select_locks(["runtime-lock.txt"])[0]
        target, original = _copy_lock(tmp_path, spec.name)

        def untouched_generator(command: list[str], root: Path) -> None:
            return None

        with pytest.raises(ValueError, match="does not start"):
            mod.refresh_lock(
                spec, tmp_path, uvx="uvx", uv="uv", runner=untouched_generator
            )
        assert target.read_text(encoding="utf-8") == original

    def test_default_runner_executes_in_the_repository_root(
        self, tmp_path: Path
    ) -> None:
        marker = tmp_path / "ran-here"
        mod._run([sys.executable, "-c", "open('ran-here', 'w').close()"], tmp_path)
        assert marker.is_file()


