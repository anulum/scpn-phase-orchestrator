class TestPreservedPrefix:
    def test_licence_block_before_pip_compile_header(self) -> None:
        text = (REQUIREMENTS / "runtime-lock.txt").read_text(encoding="utf-8")
        prefix = mod.preserved_prefix(text, "pip-compile")
        first_line = prefix.splitlines()[0]
        assert first_line.startswith("# SPDX-")
        assert first_line.endswith("AGPL-3.0-or-later")
        assert text[len(prefix) :].startswith("#\n" + mod.PIP_COMPILE_HEADER)

    def test_extra_separator_line_stays_in_the_prefix(self) -> None:
        text = (REQUIREMENTS / "audit-tools.txt").read_text(encoding="utf-8")
        prefix = mod.preserved_prefix(text, "pip-compile")
        assert prefix.endswith("dependency lock\n#\n")
        assert text[len(prefix) :].startswith("#\n" + mod.PIP_COMPILE_HEADER)

    def test_no_prefix_when_file_starts_with_the_generator_header(self) -> None:
        pip_text = (REQUIREMENTS / "dev-lock.txt").read_text(encoding="utf-8")
        uv_text = (REQUIREMENTS / "dev-lock-windows-ffi-py312.txt").read_text(
            encoding="utf-8"
        )
        assert mod.preserved_prefix(pip_text, "pip-compile") == ""
        assert mod.preserved_prefix(uv_text, "uv") == ""

    def test_missing_header_is_refused(self) -> None:
        text = (REQUIREMENTS / "docs-tools.txt").read_text(encoding="utf-8")
        with pytest.raises(ValueError, match="not found"):
            mod.preserved_prefix(text, "pip-compile")

    def test_pip_compile_header_without_opening_hash_is_refused(self) -> None:
        text = (REQUIREMENTS / "runtime-lock.txt").read_text(encoding="utf-8")
        broken = text.replace("#\n" + mod.PIP_COMPILE_HEADER, mod.PIP_COMPILE_HEADER)
        with pytest.raises(ValueError, match="opening"):
            mod.preserved_prefix(broken, "pip-compile")

    def test_header_on_first_line_without_opening_hash_is_refused(self) -> None:
        with pytest.raises(ValueError, match="opening"):
            mod.preserved_prefix(
                mod.PIP_COMPILE_HEADER + " with Python 3.12\n", "pip-compile"
            )

    @pytest.mark.parametrize(
        "name", ["runtime-lock.txt", "audit-tools.txt", "studio-sdk.txt"]
    )
    def test_restore_rebuilds_committed_bytes(self, name: str) -> None:
        text = (REQUIREMENTS / name).read_text(encoding="utf-8")
        prefix = mod.preserved_prefix(text, "pip-compile")
        regenerated = text[len(prefix) :]
        assert mod.restore_prefix(prefix, regenerated, "pip-compile") == text

    def test_restore_refuses_text_the_generator_does_not_own(self) -> None:
        text = (REQUIREMENTS / "runtime-lock.txt").read_text(encoding="utf-8")
        prefix = mod.preserved_prefix(text, "pip-compile")
        with pytest.raises(ValueError, match="does not start"):
            mod.restore_prefix(prefix, text, "pip-compile")


