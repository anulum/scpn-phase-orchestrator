class TestCommands:
    def test_pip_compile_runs_pinned_pip_tools_under_the_lock_interpreter(
        self,
    ) -> None:
        spec = mod.select_locks(["dev-lock-py313.txt"])[0]
        command = mod.build_command(spec, uvx="/bin/uvx", uv="/bin/uv")
        assert command[:6] == [
            "/bin/uvx",
            "--python",
            "3.13",
            "--from",
            f"pip-tools=={mod.PIP_TOOLS_VERSION}",
            "pip-compile",
        ]

    def test_windows_lock_uses_uv_for_the_windows_platform(self) -> None:
        spec = mod.select_locks(["dev-lock-windows-ffi-py311.txt"])[0]
        command = mod.build_command(spec, uvx="/bin/uvx", uv="/bin/uv")
        assert command[:5] == [
            "/bin/uv",
            "pip",
            "compile",
            "--python-platform",
            "windows",
        ]
        assert command[-2:] == ["-o", "requirements/dev-lock-windows-ffi-py311.txt"]

    def test_selection_keeps_canonical_order(self) -> None:
        selected = mod.select_locks(["studio-sdk.txt", "dev-lock.txt"])
        assert [spec.name for spec in selected] == ["dev-lock.txt", "studio-sdk.txt"]
        assert mod.select_locks([]) == mod.LOCKS

    def test_unknown_lock_name_is_refused(self) -> None:
        with pytest.raises(ValueError, match="unknown lockfile"):
            mod.select_locks(["dev-lock.txt", "not-a-lock.txt"])


