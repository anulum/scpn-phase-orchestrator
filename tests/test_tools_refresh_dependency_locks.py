def _cli(
    *args: str, env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args],
        capture_output=True,
        text=True,
        check=False,
        env=env,
    )


class TestCli:
    def test_list_names_every_lock_with_its_interpreter(self) -> None:
        result = _cli("--list")
        assert result.returncode == 0
        lines = result.stdout.splitlines()
        assert len(lines) == len(mod.LOCKS)
        assert "requirements/dev-lock-py311.txt\tpip-compile\tpython 3.11" in lines

    def test_dry_run_prints_commands_without_touching_files(self) -> None:
        before = (REQUIREMENTS / "pqc-lock.txt").read_bytes()
        result = _cli("--dry-run", "--only", "pqc-lock.txt")
        assert result.returncode == 0
        assert result.stdout.strip() == " ".join(
            mod.build_command(mod.select_locks(["pqc-lock.txt"])[0], uvx="uvx", uv="uv")
        )
        assert (REQUIREMENTS / "pqc-lock.txt").read_bytes() == before

    def test_unknown_lock_exits_with_usage_status(self) -> None:
        result = _cli("--only", "missing.txt")
        assert result.returncode == 2
        assert "unknown lockfile(s): missing.txt" in result.stderr

    def test_missing_uvx_stops_before_any_generator_runs(self, tmp_path: Path) -> None:
        env = dict(os.environ)
        env["PATH"] = str(tmp_path)
        before = (REQUIREMENTS / "pqc-lock.txt").read_bytes()
        result = _cli("--only", "pqc-lock.txt", env=env)
        assert result.returncode == 1
        assert "uvx is required on PATH" in result.stderr
        assert (REQUIREMENTS / "pqc-lock.txt").read_bytes() == before

    def test_in_process_list_and_dry_run(
        self, capsys: pytest.CaptureFixture[str]
    ) -> None:
        assert mod.main(["--list", "--only", "mojo-lock.txt"]) == 0
        assert capsys.readouterr().out == (
            "requirements/mojo-lock.txt\tpip-compile\tpython 3.12\n"
        )
        assert mod.main(["--dry-run", "--only", "dev-lock-windows-ffi-py312.txt"]) == 0
        printed = capsys.readouterr().out.strip()
        assert printed.startswith("uv pip compile --python-platform windows")

    def test_in_process_unknown_lock_returns_usage_status(
        self, capsys: pytest.CaptureFixture[str]
    ) -> None:
        assert mod.main(["--only", "missing.txt"]) == 2
        assert "unknown lockfile(s): missing.txt" in capsys.readouterr().err

    def test_executable_lookup_uses_path(self) -> None:
        assert Path(mod._executable(Path(sys.executable).name)).is_file()
        with pytest.raises(SystemExit, match="is required on PATH"):
            mod._executable("spo-no-such-executable-for-lock-refresh")

    def test_script_entry_point_exits_with_main_status(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.setattr(sys, "argv", [str(SCRIPT), "--list"])
        with pytest.raises(SystemExit) as excinfo:
            runpy.run_path(str(SCRIPT), run_name="__main__")
        assert excinfo.value.code == 0

    def test_main_refreshes_selected_locks_in_order(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        calls: list[tuple[str, bool]] = []
        monkeypatch.setattr(mod, "_executable", lambda name: f"/opt/{name}")

        def record(
            spec: object, root: Path, *, uvx: str, uv: str, upgrade: bool
        ) -> None:
            assert (root, uvx, uv) == (mod.ROOT, "/opt/uvx", "/opt/uv")
            calls.append((spec.name, upgrade))

        monkeypatch.setattr(mod, "refresh_lock", record)
        assert mod.main(["--only", "julia-lock.txt", "--only", "dev-lock.txt"]) == 0
        assert calls == [("dev-lock.txt", False), ("julia-lock.txt", False)]
        calls.clear()
        assert mod.main(["--upgrade", "--only", "pqc-lock.txt"]) == 0
        assert calls == [("pqc-lock.txt", True)]


class TestUpgrade:
    @pytest.mark.parametrize("spec", mod.LOCKS, ids=lambda spec: spec.name)
    def test_upgrade_adds_only_the_flag_before_the_recorded_arguments(
        self, spec: object
    ) -> None:
        plain = mod.build_command(spec, uvx="uvx", uv="uv")
        upgraded = mod.build_command(spec, uvx="uvx", uv="uv", upgrade=True)
        index = len(plain) - len(spec.arguments)
        assert upgraded == [*plain[:index], "--upgrade", *plain[index:]]

    def test_dry_run_shows_the_upgrade_flag(
        self, capsys: pytest.CaptureFixture[str]
    ) -> None:
        assert mod.main(["--dry-run", "--upgrade", "--only", "pqc-lock.txt"]) == 0
        printed = capsys.readouterr().out.split()
        assert printed[printed.index("pip-compile") + 1] == "--upgrade"

    def test_refresh_lock_forwards_upgrade_to_the_generator(
        self, tmp_path: Path
    ) -> None:
        spec = mod.select_locks(["runtime-lock.txt"])[0]
        target, original = _copy_lock(tmp_path, spec.name)
        prefix = mod.preserved_prefix(original, "pip-compile")
        commands: list[list[str]] = []

        def rewrite(command: list[str], root: Path) -> None:
            commands.append(command)
            target.write_text(original[len(prefix) :], encoding="utf-8")

        mod.refresh_lock(
            spec, tmp_path, uvx="uvx", uv="uv", upgrade=True, runner=rewrite
        )
        assert "--upgrade" in commands[0]
        assert target.read_text(encoding="utf-8") == original
