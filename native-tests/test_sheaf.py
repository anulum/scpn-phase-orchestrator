def test_native_keyword_and_documented_defaults_advance_real_state() -> None:
    """Documented defaults and keyword controls produce exact elapsed intervals.

    Every handwritten binding is exercised here or by the buffer and batch
    cases. The extra uncovered function at #[pymethods] is generated by PyO3;
    it has no separate handwritten entry point that a real call can select.
    """
    signature = inspect.signature(spo_kernel.PySheafUPDEStepper)
    assert signature.parameters["dt"].default == 0.01
    assert signature.parameters["n_substeps"].default == 1
    assert signature.parameters["atol"].default == 1e-6
    assert signature.parameters["rtol"].default == 1e-3
    phase = np.array([0.2])
    frequency = np.array([1.0])
    maps = np.zeros(1)
    target = np.zeros(1)
    default = spo_kernel.PySheafUPDEStepper(n=1, d=1)
    configured = spo_kernel.PySheafUPDEStepper(
        n=1, d=1, dt=0.02, method="rk45", n_substeps=3, atol=1e-10, rtol=1e-10
    )
    np.testing.assert_allclose(
        default.run(phase, frequency, maps, 0.0, target, 3), [0.23], atol=1e-15
    )
    np.testing.assert_allclose(
        configured.run(phase, frequency, maps, 0.0, target, 3), [0.26], atol=1e-15
    )
    np.testing.assert_array_equal(phase, [0.2])


@pytest.mark.parametrize("method", ["euler", "rk4", "rk45"])
@pytest.mark.parametrize("substeps", [1, 3])
@pytest.mark.parametrize("operation", ["step", "run"])
def test_native_methods_advance_configured_horizon(
    method: str, substeps: int, operation: str
) -> None:
    """Native geometry and substeps preserve exact uncoupled elapsed time."""
    native = spo_kernel.PySheafUPDEStepper(2, 2, 0.01, method, substeps)
    phases = np.array([0.2, 0.5, 0.8, 1.1])
    omegas = np.array([1.0, -0.5, 0.8, 1.2])
    maps = np.zeros(16)
    psi = np.zeros(2)
    steps = 1 if operation == "step" else 7
    output = (
        native.step(phases, omegas, maps, 0.0, psi)
        if operation == "step"
        else native.run(phases, omegas, maps, 0.0, psi, steps)
    )
    np.testing.assert_allclose(
        output, phases + steps * 0.01 * omegas, atol=2e-15, rtol=0
    )
    assert native.n == 2 and native.d == 2
    assert 0.0 < native.last_dt <= 0.01
    assert output.dtype == np.float64 and output.shape == (4,)
    assert not np.shares_memory(output, phases)
    np.testing.assert_array_equal(phases, [0.2, 0.5, 0.8, 1.1])


@pytest.mark.parametrize("method", ["euler", "rk4", "rk45"])
@pytest.mark.parametrize("operation", ["step", "run"])
def test_native_shared_readonly_inputs_follow_entry_equation(
    method: str, operation: str
) -> None:
    """Aliased readonly phase, frequency, map and target buffers remain unchanged."""
    shared = np.array([0.4])
    shared.setflags(write=False)
    native = spo_kernel.PySheafUPDEStepper(1, 1, 0.01, method)
    output = (
        native.step(shared, shared, shared, 0.0, shared)
        if operation == "step"
        else native.run(shared, shared, shared, 0.0, shared, 5)
    )
    # N=D=1 map couples a phase to itself, so the exact derivative is omega.
    np.testing.assert_allclose(
        output, [0.404 if operation == "step" else 0.42], atol=1e-15, rtol=0
    )
    np.testing.assert_array_equal(shared, [0.4])
    assert not np.shares_memory(output, shared)


@pytest.mark.parametrize("field", ["phases", "omegas", "maps", "psi"])
@pytest.mark.parametrize("fault", ["short", "nonfinite", "strided", "dtype", "matrix"])
@pytest.mark.parametrize("operation", ["step", "run", "zero"])
def test_native_buffer_refusal_preserves_solver_and_recovers(
    field: str, fault: str, operation: str
) -> None:
    """Real malformed buffers refuse even zero batches; the same solver recovers."""
    buffers = {
        "phases": np.array([0.1, 0.2, 0.3, 0.4]),
        "omegas": np.ones(4),
        "maps": np.zeros(16),
        "psi": np.zeros(2),
    }
    saved = {name: values.copy() for name, values in buffers.items()}
    invalid = buffers[field].copy()
    if fault == "short":
        invalid = invalid[:-1]
    elif fault == "nonfinite":
        invalid[0] = np.inf
    elif fault == "strided":
        storage = np.repeat(invalid, 2)
        invalid = storage[::2]
    elif fault == "matrix":
        invalid = invalid.reshape(1, -1)
    else:
        invalid = invalid.astype(np.float32)
    buffers[field] = invalid
    native = spo_kernel.PySheafUPDEStepper(2, 2, 0.01, "rk45")
    expected_error = TypeError if fault in ("dtype", "matrix") else ValueError
    with pytest.raises(expected_error):
        if operation == "step":
            native.step(
                buffers["phases"],
                buffers["omegas"],
                buffers["maps"],
                0.0,
                buffers["psi"],
            )
        else:
            native.run(
                buffers["phases"],
                buffers["omegas"],
                buffers["maps"],
                0.0,
                buffers["psi"],
                0 if operation == "zero" else 2,
            )
    assert native.last_dt == 0.01
    buffers = saved
    output = native.run(
        buffers["phases"], buffers["omegas"], buffers["maps"], 0.0, buffers["psi"], 2
    )
    np.testing.assert_allclose(output, [0.12, 0.22, 0.32, 0.42], atol=1e-15, rtol=0)
    np.testing.assert_array_equal(saved["phases"], [0.1, 0.2, 0.3, 0.4])


