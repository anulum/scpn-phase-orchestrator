@pytest.mark.parametrize("method", ["euler", "rk4", "rk45"])
@pytest.mark.parametrize("operation", ["step", "run"])
def test_native_numerical_refusal_recovers_on_same_instance(
    method: str, operation: str
) -> None:
    """Nonfinite output refusal preserves the complete call's timestep and input.

    Native adaptive proposals are capped by finite positive configured dt
    after a finite clamped factor, so the non-finite proposal arm is unreachable.
    Public subnormal-interval cases exercise actual zero-proposal refusal;
    these native overflow cases exercise producer refusal and recovery.
    """
    native = spo_kernel.PySheafUPDEStepper(1, 1, 10.0, method)
    phase = np.zeros(1)
    huge = np.full(1, 1e308)
    with pytest.raises(ValueError):
        if operation == "step":
            native.step(phase, huge, np.zeros(1), 0.0, np.zeros(1))
        else:
            native.run(phase, huge, np.zeros(1), 0.0, np.zeros(1), 2)
    assert native.last_dt == 10.0
    np.testing.assert_array_equal(phase, [0.0])
    np.testing.assert_allclose(
        native.run(phase, np.full(1, 0.1), np.zeros(1), 0.0, np.zeros(1), 2),
        [2.0],
        atol=1e-14,
        rtol=0,
    )


@pytest.mark.parametrize("method", ["euler", "rk4", "rk45"])
@pytest.mark.parametrize("operation", ["step", "run"])
@pytest.mark.parametrize(
    ("phase_value", "omega"),
    [(-1e-300, 0.0), (0.0, -1e-15), (-2 * np.pi, 0.0), (-4 * np.pi, 0.0)],
)
def test_native_torus_rounding_and_negative_crossings_return_zero(
    method: str, operation: str, phase_value: float, omega: float
) -> None:
    """Negative crossings and exact torus multiples return positive zero.

    After '%' and conditional addition, finite values are nonnegative and
    the rounded upper endpoint is mapped to zero. Thus the final native
    negative/upper-endpoint guards cannot fail with admitted real input.
    These cases cover the nearest producer behavior without a fake output.
    """
    native = spo_kernel.PySheafUPDEStepper(1, 1, 0.01, method)
    phase = np.array([phase_value])
    frequency = np.array([omega])
    output = (
        native.step(phase, frequency, np.zeros(1), 0.0, np.zeros(1))
        if operation == "step"
        else native.run(phase, frequency, np.zeros(1), 0.0, np.zeros(1), 3)
    )
    np.testing.assert_array_equal(output, [0.0])
    assert not np.any(np.signbit(output))
    np.testing.assert_array_equal(phase, [phase_value])


@pytest.mark.parametrize("method", ["euler", "rk4", "rk45"])
def test_public_uses_installed_native_class_and_matching_equation(method: str) -> None:
    """Public matrix dispatch preserves real native anisotropic forcing."""
    public = SheafUPDEEngine(2, 2, 0.01, method=method)
    assert isinstance(public._rust, spo_kernel.PySheafUPDEStepper)
    phases = np.array([[0.1, 0.4], [0.9, 1.2]])
    frequencies = np.array([[0.2, -0.1], [0.05, 0.15]])
    maps = np.zeros((2, 2, 2, 2))
    maps[0, 1] = [[0.3, 0.1], [0.2, 0.4]]
    maps[1, 0] = [[0.5, 0.0], [0.1, 0.2]]
    psi = np.array([0.7, 1.0])
    direct = spo_kernel.PySheafUPDEStepper(2, 2, 0.01, method)
    output = public.run(phases, frequencies, maps, 0.2, psi, 5)
    native = direct.run(phases.ravel(), frequencies.ravel(), maps.ravel(), 0.2, psi, 5)
    np.testing.assert_allclose(output.ravel(), native, atol=1e-15, rtol=0)
    np.testing.assert_array_equal(phases, [[0.1, 0.4], [0.9, 1.2]])


def test_native_adaptive_full_horizon_matches_nonlinear_reference() -> None:
    """Repeated forced RK45 intervals agree with an independent high-order solver."""
    native = spo_kernel.PySheafUPDEStepper(1, 1, 0.4, "rk45", atol=1e-12, rtol=1e-12)
    phase = np.array([0.1])
    frequency = np.array([0.3])
    maps = np.zeros(1)
    psi = np.array([1.2])
    reference = solve_ivp(
        lambda _t, y: 0.3 + 2.0 * np.sin(1.2 - y),
        (0.0, 2.0),
        phase,
        method="DOP853",
        atol=1e-13,
        rtol=1e-13,
    ).y[:, -1]
    output = native.run(phase, frequency, maps, 2.0, psi, 5)
    np.testing.assert_allclose(output, reference, atol=2e-11, rtol=0)
    assert 0.0 < native.last_dt < 0.4


